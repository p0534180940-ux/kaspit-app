export function normalizeText(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[\u05F3\u05F4'"`׳״]/g, '')
    .replace(/[-–—_.,;:!?()\[\]/\\|+*]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// "שלד" המילה: הסרת אותיות התנועה (א,ה,ו,י) והרווחים,
// כדי שהקלדה בלי אותיות תנועה (למשל "נטרנט" במקום "אינטרנט") תזוהה גם כן
export function skeleton(text) {
  return normalizeText(text).replace(/ך/g, 'כ').replace(/ם/g, 'מ').replace(/ן/g, 'נ').replace(/ף/g, 'פ').replace(/ץ/g, 'צ').replace(/[אהוי]/g, '').replace(/\s+/g, '');
}

export function matchMerchant(text, type) {
  const norm = normalizeText(text);
  if (!norm) return null;
  const map = type === 'income' ? INCOME_MERCHANT_MAP : MERCHANT_MAP;
  let best = null;
  let bestLen = 0;
  for (const key in map) {
    const k = normalizeText(key);
    if (k.length > bestLen && norm.includes(k)) {
      best = map[key];
      bestLen = k.length;
    }
  }
  return best ? { category: best, matchLength: bestLen } : null;
}