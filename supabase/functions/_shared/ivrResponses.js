// עזרי תגובות למערכת הטלפונית (TLivr / טכנוליין)
// כל בקשת קלט מקבלת שם פרמטר ייחודי לשלב, ונשמרת בסשן השיחה —
// כך הפרמטרים שנצברו בשיחה לא מבלבלים את הניתוב ואין חזרה לשלב קודם.

export function say(text) {
  return Response.json({ type: 'simpleMessage', files: [{ text }] });
}

export async function menu(ctx, handler, keys, text, times = 3, timeout = 8) {
  return ctx.ask(handler, (name) => ({
    type: 'simpleMenu',
    name,
    enabledKeys: keys,
    times,
    timeout,
    errorReturn: 'ERROR',
    setMusic: 'no',
    files: [{ text }],
  }));
}

// דיווח קולי — המרכזיה רק מקליטה לקובץ, והתמלול מתבצע אצלנו (זול משמעותית)
export async function askVoice(ctx, handler, prompt, max = 10) {
  // מצב גיבוי: אם התמלול אצלנו לא זמין (למשל נגמרו הקרדיטים), המרכזיה מתמללת
  if (ctx.sttMode === 'yemot') {
    return ctx.ask(
      handler,
      // התמלול המקורי של המרכזיה (type: stt) — האיכות הטובה ביותר שהייתה
      (name) => ({
        type: 'stt',
        name,
        max: Math.min(Number(max) || 10, 10),
        min: 1,
        files: [{ text: prompt }],
      }),
      'speech'
    );
  }
  return ctx.ask(
    handler,
    (name) => ({
      type: 'record',
      name,
      path: ctx.recFolder,
      fileName: ctx.recFileName(name),
      lengthMin: 1,
      lengthMax: Math.min(Number(max) || 10, 30),
      confirmType: 'no',
      saveOnHangup: 'yes',
      setMusic: 'no',
      files: [{ text: prompt }],
    }),
    'record'
  );
}

// קליטת ספרות — סולמית מסיימת, בלי בקשת אישור מהמרכזיה.
// בהקלדת טקסט (T9) הסולמית משמשת להחלפת מודל, ולכן שולחים skipKey='no'
// והקליטה מסתיימת לאחר שקט קצר.
export async function askDigits(ctx, handler, prompt, max = 10, min = 1, skipKey = '#') {
  return ctx.ask(handler, (name) => ({
    type: 'getDTMF',
    name,
    max,
    min,
    // בהקלדת טקסט (T9) נדרש זמן המתנה ארוך יותר בין הקשה להקשה,
    // אחרת המרכזיה קוטעת את הקלט ונשמרות רק האותיות הראשונות
    timeout: skipKey === 'no' ? 8 : 6,
    skipKey,
    confirmType: 'no',
    setMusic: 'no',
    files: [{ text: prompt }],
  }));
}

