let INDEX = null;

function buildIndex() {
  const set = new Set();
  const add = (s) => { const t = String(s || '').trim(); if (t && /[\u05D0-\u05EA]/.test(t)) set.add(t); };
  Object.keys(MERCHANT_MAP).forEach(add);
  Object.keys(INCOME_MERCHANT_MAP).forEach(add);
  Object.values(EXPENSE_LABELS).forEach((v) => typeof v === 'string' && add(v));
  Object.values(INCOME_LABELS).forEach((v) => typeof v === 'string' && add(v));
  Object.values(EXTRA_LABELS).forEach(add);
  EXTRA_TERMS.forEach(add);
  const bySkeleton = new Map();
  const entries = [];
  for (const term of set) {
    const sk = skeleton(term);
    if (sk.length < 2) continue;
    const e = { term, sk };
    entries.push(e);
    if (!bySkeleton.has(sk)) bySkeleton.set(sk, []);
    bySkeleton.get(sk).push(e);
  }
  return { entries, bySkeleton };
}

export function getVocab() {
  if (!INDEX) INDEX = buildIndex();
  return INDEX;
}