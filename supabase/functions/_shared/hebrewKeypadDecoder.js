// ------------------------------------------------ בניית המילון
const entries = []; // { text, words:[normalized...], weight }
const seen = new Map();

function hebrewOnly(word) {
  return [...word].filter((c) => /[א-ת]/.test(c)).join("");
}

// להשוואה: אות סופית = אות רגילה (כדי לסלוח למי שהקיש מ במקום ם)
function normalize(word) {
  return [...word]
    .map((c) => FROM_FINAL[c] || c)
    .filter((c) => /[א-ת]/.test(c)) // רק אותיות עבריות (מוריד גרש, מקף וכו')
    .join("");
}

export function addWords(list, weight = 5) {
  for (let raw of list) {
    raw = raw.replace(/[֑-ׇ]/g, "").trim(); // בלי ניקוד
    if (!raw) continue;
    let w = weight;
    if (raw.includes("|")) {
      const [t, wt] = raw.split("|");
      raw = t.trim();
      w = parseFloat(wt) || weight;
    }
    const rawWords = raw.split(/\s+/).map(hebrewOnly).filter(Boolean);
    const words = rawWords.map(normalize);
    if (!words.length) continue;
    if (seen.has(raw)) {
      seen.get(raw).weight += w;
      continue;
    }
    const e = { text: raw, words, rawWords, weight: w };
    entries.push(e);
    seen.set(raw, e);
  }
}

addWords(
  DICTIONARY.split("\n").filter((l) => l.trim() && !l.trim().startsWith("#")),
  1
);

// ------------------------------------------------ פירוק ההקשות
// מפצל רצף לחיצות על אותו מקש לכל החלוקות האפשריות לאותיות.
// דוגמה: "555" על מקש 5 (י כ ל) -> ["ל", "יכ", "כי", "ייי"]
function runOptions(digit, count, keys, includeDot) {
  let letters = keys[digit];
  if (!letters) return [""];
  if (!includeDot) letters = letters.filter((c) => c !== ".");
  const k = letters.length;
  const results = [];
  // הקריאה "הרגילה": כל הרצף = אות אחת (מחזורי, כמו בטלפון)
  results.push(letters[(count - 1) % k]);
  // שאר החלוקות (למקרה שלא הקישו * בין שתי אותיות באותו מקש)
  const rec = (left, acc) => {
    if (results.length > 60) return;
    if (left === 0) {
      const s = acc.join("");
      if (!results.includes(s)) results.push(s);
      return;
    }
    for (let p = 1; p <= Math.min(k, left); p++) rec(left - p, [...acc, letters[p - 1]]);
  };
  if (count <= 8) rec(count, []);
  return results;
}

// מקבל הקשות של מילה אחת ומחזיר { literal, options[] }
function wordCandidates(keysStr, keys) {
  const chunks = keysStr.split(/[*\s]+/).filter(Boolean); // * או רווח = הפרדה
  let combos = [""];
  let literal = "";
  for (const chunk of chunks) {
    const runs = chunk.match(/(\d)\1*/g) || [];
    for (const run of runs) {
      const opts = runOptions(run[0], run.length, keys, false);
      literal += opts[0];
      const next = [];
      for (const c of combos) for (const o of opts) {
        if (next.length < 3000) next.push(c + o);
      }
      combos = next;
    }
  }
  const options = [...new Set(combos.map(normalize))];
  return { literalRaw: literal, literal: normalize(literal), options };
}

// ------------------------------------------------ התאמה למילון
// האם המילה מהמילון מתאימה לאותיות שהוקשו, כשמותר לדלג רק על א/ה/ו/י
function matchesWithoutVowels(typed, dictWord, inPhrase) {
  // אות אחת מותרת כקיצור רק בתוך ביטוי (למשל "רמ ל" = רמי לוי)
  if (typed.length < 2 && dictWord.length > 2 && !inPhrase) return -1;
  if (typed[0] !== dictWord[0]) return -1; // האות הראשונה חייבת להיות זו שהוקשה
  let i = 0, skipped = 0;
  for (const c of dictWord) {
    if (i < typed.length && typed[i] === c) i++;
    else if (VOWELS.has(c)) skipped++;
    else return -1;
  }
  if (i !== typed.length) return -1;
  return skipped;
}

// ציון התאמה של מילה מהמילון להקשות מילה אחת
function scoreWord(cand, dictWord, inPhrase = false, rawWord = null) {
  if (rawWord && rawWord === cand.literalRaw) return 100; // בדיוק כולל סופיות
  if (dictWord === cand.literal) return 95;               // רק סופית/רגילה התחלפו
  let best = -1;
  for (let idx = 0; idx < cand.options.length; idx++) {
    const t = cand.options[idx];
    if (t === dictWord) best = Math.max(best, 85);
    const sk = matchesWithoutVowels(t, dictWord, inPhrase);
    if (sk >= 0) best = Math.max(best, (idx === 0 ? 75 : 60) - sk * 3);
  }
  return best;
}

// ------------------------------------------------ פענוח
function finalize(word) {
  if (!word || word.length < 2) return word; // אות בודדת נשארת רגילה
  const arr = [...word].map((c) => FROM_FINAL[c] || c);
  const last = arr.length - 1;
  arr[last] = TO_FINAL[arr[last]] || arr[last];
  return arr.join("");
}

function decodeHebrew(keysStr) {
  const groups = keysStr.split("0").map((g) => g.trim()).filter((g) => g.replace(/[*\s]/g, ""));
  const cands = groups.map((g) => wordCandidates(g, HEBREW_KEYS));
  const out = [];
  const alternatives = [];
  let confidenceSum = 0;
  let i = 0;
  while (i < cands.length) {
    // מחפשים את ההתאמה הטובה ביותר שמתחילה במילה i (ביטוי של עד 4 מילים)
    const scored = [];
    for (const e of entries) {
      const n = e.words.length;
      if (i + n > cands.length) continue;
      let total = 0, ok = true;
      for (let j = 0; j < n; j++) {
        const s = scoreWord(cands[i + j], e.words[j], n > 1, e.rawWords[j]);
        if (s < 0) { ok = false; break; }
        total += s;
      }
      if (!ok) continue;
      const avg = total / n;
      // ביטוי ארוך שמתאים במלואו עדיף, ואחר כך המשקל במילון
      scored.push({ e, n, avg, rank: total + Math.log2(1 + e.weight) * 2 });
    }
    scored.sort((a, b) => b.rank - a.rank);
    if (scored.length) {
      const top = scored[0];
      out.push(top.e.text);
      confidenceSum += top.avg * top.n;
      alternatives.push(scored.slice(0, 5).map((s) => s.e.text));
      i += top.n;
    } else {
      // אין במילון - מחזירים בדיוק מה שהוקש, בלי להמציא
      const lit = finalize(cands[i].literalRaw);
      out.push(lit);
      alternatives.push([lit]);
      i += 1;
    }
  }
  const confidence = cands.length ? Math.round(confidenceSum / cands.length) : 0;
  return { text: out.join(" "), alternatives, confidence };
}

function decodeLiteral(keysStr, keys) {
  return keysStr
    .split("0")
    .map((g) => wordCandidates(g, keys).literalRaw)
    .join(" ");
}

/**
 * מפענח את כל ההקשות.
 * @param {string} input רצף הקשות, למשל "745055552225" או "7 4 5 0 5555 222 5"
 * @returns {{text:string, confidence:number, alternatives:string[][], parts:object[]}}
 *   text        - הטקסט המפוענח
 *   confidence  - 0..100 (מתחת ל-60 כדאי לשאול את המשתמש לאישור)
 *   alternatives- אפשרויות נוספות לכל מילה (לשאלת "האם התכוונת ל...")
 */
export function decode(input) {
  const clean = String(input).replace(/[^0-9*#\s]/g, "");
  // # מחליף מצב: עברית -> מספרים -> אנגלית -> עברית
  const segments = [];
  let mode = 0, buf = "";
  for (const ch of clean) {
    if (ch === "#") {
      segments.push({ mode, buf });
      buf = "";
      mode = (mode + 1) % 3;
    } else buf += ch;
  }
  segments.push({ mode, buf });

  const parts = [];
  for (const { mode, buf } of segments) {
    if (!buf.replace(/[\s*]/g, "")) continue;
    if (mode === 0) parts.push({ mode: "hebrew", ...decodeHebrew(buf) });
    else if (mode === 1) parts.push({ mode: "numbers", text: buf.replace(/[^0-9]/g, ""), confidence: 100, alternatives: [] });
    else parts.push({ mode: "english", text: decodeLiteral(buf, ENGLISH_KEYS), confidence: 100, alternatives: [] });
  }
  return {
    text: parts.map((p) => p.text).join(" ").trim(),
    confidence: parts.length ? Math.min(...parts.map((p) => p.confidence)) : 0,
    alternatives: parts.flatMap((p) => p.alternatives),
    parts,
  };
}

// מחזיר את רצף ההקשות הנכון למילה (טוב לבדיקות ולמדריך)
export function encode(text) {
  const letterToPress = {};
  for (const [d, letters] of Object.entries(HEBREW_KEYS))
    if (d !== "3") letters.forEach((c, i) => (letterToPress[c] = d.repeat(i + 1)));
  return text
    .split(/\s+/)
    .map((w) => {
      let prev = "";
      return [...hebrewOnly(w)]
        .map((c) => {
          const p = letterToPress[c] || "";
          const sep = prev && p && prev[0] === p[0] ? "*" : "";
          prev = p;
          return sep + p;
        })
        .join("");
    })
    .join("0");
}

