// הקלדת מילים שלמות במקשי הטלפון (T9)
// עברית: 1=א ב ג ונקודה, 2=ד ה ו, 6=ז ח ט, 5=י כ ל, 4=מ נ, 9=ס ע פ, 8=צ ק, 7=ר ש ת, 0=רווח
// לחיצה אחת = אות ראשונה, שתיים = שנייה, שלוש = שלישית.
// כוכבית אחת = מפריד בין שתי אותיות שנמצאות על אותו מקש.
// סולמית = החלפת מודל לפי הסדר: עברית ← מספרים ← אנגלית ← עברית (גם שתי כוכביות מחליפות מודל).

import { decodeKeypad } from './t9Seed.js';

const HE = {
  '1': ['א', 'ב', 'ג', '.'],
  '2': ['ד', 'ה', 'ו'],
  '3': ['א', 'ב', 'ג', '.'], // בטלפונים רבים מקש 1 מגיע כ-3, ולכן הוא נחשב כמו מקש 1
  '6': ['ז', 'ח', 'ט'],
  '5': ['י', 'כ', 'ך', 'ל'],
  '4': ['מ', 'ם', 'נ', 'ן'],
  '9': ['ס', 'ע', 'פ', 'ף'],
  '8': ['צ', 'ץ', 'ק'],
  '7': ['ר', 'ש', 'ת'],
};

const EN = {
  '1': ['@', '.', '_', '-'],
  '2': ['a', 'b', 'c'],
  '3': ['d', 'e', 'f'],
  '4': ['g', 'h', 'i'],
  '5': ['j', 'k', 'l'],
  '6': ['m', 'n', 'o'],
  '7': ['p', 'q', 'r', 's'],
  '8': ['t', 'u', 'v'],
  '9': ['w', 'x', 'y', 'z'],
};

const MODES = ['he', 'num', 'en'];

function nextMode(mode) {
  const i = MODES.indexOf(mode);
  return MODES[(i + 1) % MODES.length];
}

// עברית: המפענח החדש (מילון, אותיות סופיות, בלי ניחוש). אנגלית (כתובת מייל): הפענוח הישיר שלמטה.
export function decodeT9(sequence, startMode = 'he') {
  if (startMode === 'he') return decodeKeypad(sequence).text;
  return decodeDirect(sequence, startMode);
}

function decodeDirect(sequence, startMode) {
  const seq = String(sequence || '').replace(/[^0-9*#]/g, '');
  let mode = MODES.includes(startMode) ? startMode : 'he';
  let out = '';
  let i = 0;

  while (i < seq.length) {
    const c = seq[i];

    // סולמית — החלפת מודל
    if (c === '#') {
      mode = nextMode(mode);
      i += 1;
      continue;
    }

    let count = 0;
    while (seq[i + count] === c) count += 1;

    // כוכבית אחת = מפריד בלבד. שתי כוכביות ומעלה = החלפת מודל (חלופה לסולמית)
    if (c === '*') {
      const switches = Math.floor(count / 2);
      for (let s = 0; s < switches; s++) mode = nextMode(mode);
      i += count;
      continue;
    }

    // מודל מספרים — כל לחיצה היא ספרה
    if (mode === 'num') {
      out += c.repeat(count);
      i += count;
      continue;
    }

    // אפס = רווח אחד, גם אם הוקש כמה פעמים
    if (c === '0') {
      out += ' ';
      i += count;
      continue;
    }

    const table = mode === 'he' ? HE : EN;
    const letters = table[c];
    // לחיצות עודפות (למשל 5555 במקש של שלוש אותיות) נשארות על האות האחרונה, ולא חוזרות לראשונה
    if (letters) out += letters[Math.min(count, letters.length) - 1];
    i += count;
  }

  return out.replace(/\s+/g, ' ').trim();
}

