// נרמול טקסט: הסרת מקפים, גרשיים, נקודות ורווחים כפולים — כדי ש"רב-קו" יזוהה כמו "רב קו"
export function normalizeText(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[\u05F3\u05F4'"`׳״]/g, '')
    .replace(/[-–—_.,;:!?()\[\]/\\|+*]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// מחזיר את מזהה הקטגוריה לפי ההתאמה הארוכה ביותר במילון
export function matchMerchant(text, type) {
  const norm = normalizeText(text);
  if (!norm) return null;
  const map = type === 'income' ? INCOME_MERCHANT_MAP : MERCHANT_MAP;
  let best = null;
  let bestLen = 0;
  for (const key in map) {
    const k = normalizeText(key);
    if (k.length > bestLen && norm.includes(k)) {
      best = map[key];
      bestLen = k.length;
    }
  }
  return best ? { category: best, matchLength: bestLen } : null;
}